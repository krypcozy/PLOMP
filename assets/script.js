// Countdown to next chapter — set your real drop date/time here (ISO format)
const target = new Date("2026-08-17T19:00:00-04:00");
function tick() {
  const diff = target - new Date();
  if (diff <= 0) {
    document.getElementById('dd').textContent = '00';
    document.getElementById('hh').textContent = '00';
    document.getElementById('mm').textContent = '00';
    document.getElementById('ss').textContent = '00';
    return;
  }
  const d = Math.floor(diff / 86400000);
  const h = Math.floor(diff % 86400000 / 3600000);
  const m = Math.floor(diff % 3600000 / 60000);
  const s = Math.floor(diff % 60000 / 1000);
  document.getElementById('dd').textContent = String(d).padStart(2, '0');
  document.getElementById('hh').textContent = String(h).padStart(2, '0');
  document.getElementById('mm').textContent = String(m).padStart(2, '0');
  document.getElementById('ss').textContent = String(s).padStart(2, '0');
}
tick();
setInterval(tick, 1000);